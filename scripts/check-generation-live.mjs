import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import nextEnv from '@next/env';
import { createClient } from '@insforge/sdk';
import { PDFParse } from 'pdf-parse';
import { resumePdf } from './fixtures/resume.mjs';

nextEnv.loadEnvConfig(process.cwd());
const base = 'http://localhost:3108';
const fixtures = JSON.parse(await readFile('.env.schema-fixtures.json', 'utf8'));
assert.equal(fixtures.length, 2);
assert.ok(fixtures.every((f) => f.email === `nextrole-schema-${f.id}@example.invalid`), 'explicit disposable fixtures only');
const sessions = [];
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; };
const config = { baseUrl: process.env.NEXT_PUBLIC_INSFORGE_URL, anonKey: process.env.NEXT_PUBLIC_INSFORGE_ANON_KEY, isServerMode: true, retryCount: 0 };
for (const fixture of fixtures) {
  const login = await createClient(config).auth.signInWithPassword({ email: fixture.email, password: fixture.password });
  assert.ok(!login.error && login.data?.accessToken, 'synthetic fixture sign in');
  sessions.push({ id: fixture.id, email: fixture.email, cookie: `insforge_access_token=${login.data.accessToken}`, client: createClient({ ...config, accessToken: login.data.accessToken }) });
}
const [a, b] = sessions;
async function generate(session, updatedAt, extra = {}, origin = base) {
  const response = await fetch(base + '/api/resume/generate', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', ...(session ? { Cookie: session.cookie } : {}) }, body: JSON.stringify({ updatedAt, ...extra }) });
  return { response, body: await response.json() };
}
async function profile(session) {
  const result = await session.client.database.from('profiles').select().eq('id', session.id).maybeSingle();
  assert.ok(!result.error); return result.data;
}
try {
  check((await generate(null, 'v1')).response.status === 401, 'anonymous generation denied');
  check((await generate(a, 'v1', {}, 'https://other.invalid')).response.status === 403, 'cross origin generation denied');
  check((await generate(b, 'v1', { userId: a.id })).response.status === 404, 'foreign owner cannot be selected');
  const inserted = await a.client.database.from('profiles').insert([{ id: a.id, email: a.email, full_name: 'Morgan Example', current_title: 'Software Engineer', skills: ['React', 'TypeScript', 'PostgreSQL'], years_experience: 4, work_experience: [{ company: 'Example Company', job_title: 'Software Engineer', start_date: '2022-01', end_date: null, is_current: true, responsibilities: 'Built React interfaces. Maintained PostgreSQL queries.' }], education: { degree: "Bachelor's", field_of_study: 'Computer Science', institution: 'Example University', graduation_year: 2020 } }]);
  assert.ok(!inserted.error, 'synthetic profile insert');
  const upload = await a.client.storage.from('resumes').upload(`${a.id}/resume.pdf`, resumePdf());
  assert.ok(!upload.error && upload.data, 'synthetic baseline PDF upload');
  assert.ok(!(await a.client.database.from('profiles').update({ resume_pdf_key: upload.data.key, resume_pdf_url: upload.data.url }).eq('id', a.id)).error);
  const before = await profile(a);
  check((await generate(a, 'stale')).response.status === 409, 'stale generation denied');
  const result = await generate(a, before.updated_at, { userId: b.id, profile: { full_name: 'forged' } });
  if (!result.body.success) console.log('Generation feedback:', result.response.status, result.body.error);
  check(result.response.status === 200 && result.body.success, 'production endpoint generates and persists PDF');
  check(result.response.headers.get('cache-control').includes('no-store'), 'generated metadata private');
  const after = await profile(a);
  check(after.updated_at === result.body.data.updatedAt && after.updated_at !== before.updated_at, 'new version returned for subsequent saves');
  for (const [key, value] of Object.entries(before)) if (!['resume_pdf_url', 'resume_pdf_key', 'updated_at'].includes(key)) assert.deepEqual(after[key], value, `${key} unchanged`);
  checks++;
  check((await profile(b)) === null, 'foreign profile untouched');
  const download = await fetch(base + '/api/resume/download', { headers: { Cookie: a.cookie } });
  const bytes = new Uint8Array(await download.arrayBuffer());
  check(download.ok && bytes.length === result.body.data.size, 'View Resume serves generated bytes');
  const parser = new PDFParse({ data: bytes });
  try {
    check((await parser.getInfo()).total === 1, 'persisted PDF is one page');
    const text = (await parser.getText()).text;
    check(text.includes('Morgan Example') && text.includes('Example Company') && text.includes('Example University') && text.includes('React') && !text.includes('forged'), 'PDF uses saved owner facts');
  } finally { await parser.destroy(); }
  const foreign = await b.client.storage.from('resumes').download(after.resume_pdf_key);
  check(Boolean(foreign.error), 'foreign storage download denied');
  check((await generate(a, before.updated_at)).response.status === 409, 'old version rejected after successful generation');
  const html = await (await fetch(base + '/profile', { headers: { Cookie: a.cookie } })).text();
  check(html.includes('Morgan Example') && html.includes('View Resume') && html.includes('Generate Resume') && !html.includes('generation is coming'), 'profile reload shows saved resume and live action');
  console.log(`PASS ${checks} live authenticated generation, replacement, private download and ownership checks`);
} finally {
  for (const session of sessions) {
    const removed = await session.client.storage.from('resumes').remove(`${session.id}/resume.pdf`);
    if (removed.error && removed.error.statusCode !== 404) console.log('Fixture storage cleanup requires verification');
  }
}
